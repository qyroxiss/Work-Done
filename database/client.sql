/*
  Q-WorkDone - tables of one client company (PostgreSQL 14+).

  Every client company has its own schema (e.g. wd_acme). The app runs this script with "dbo."
  replaced by that schema, when the company is created and whenever the app starts with a newer
  schema version. It is idempotent: safe to run again at any time.

  Conventions
  - Timestamps are timestamptz (absolute instants); dates the user picks are date.
  - Usernames, e-mails and codes are citext: unique and matched without regard to case.
  - Records referenced by work history are never deleted, only deactivated.
*/

/* ---------- Employees ---------- */
CREATE TABLE IF NOT EXISTS dbo.Employees (
    EmployeeId    integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    EmployeeCode  citext       NOT NULL UNIQUE,
    EmployeeName  varchar(100) NOT NULL,
    Department    varchar(100),
    Phone         varchar(30),
    Email         citext,
    JoiningDate   date,
    IsActive      boolean      NOT NULL DEFAULT true,
    CreatedAt     timestamptz  NOT NULL DEFAULT now(),
    UpdatedAt     timestamptz  NOT NULL DEFAULT now()
);

/* ---------- Users ---------- */
CREATE TABLE IF NOT EXISTS dbo.Users (
    UserId              integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ClientId            varchar(30),                     -- Client ID of the company (as in public.Clients)
    Username            citext       NOT NULL UNIQUE,
    Email               citext,                          -- optional; can be used instead of the username to sign in
    PasswordHash        varchar(255) NOT NULL,
    Role                varchar(20)  NOT NULL CHECK (Role IN ('Admin', 'Manager', 'Employee')),
    EmployeeId          integer      REFERENCES dbo.Employees (EmployeeId),
    MustChangePassword  boolean      NOT NULL DEFAULT true,
    IsActive            boolean      NOT NULL DEFAULT true,
    LastLoginAt         timestamptz,
    CreatedAt           timestamptz  NOT NULL DEFAULT now(),
    UpdatedAt           timestamptz  NOT NULL DEFAULT now(),
    -- Employee accounts must be linked to an employee record
    CONSTRAINT ck_users_employee_link CHECK (Role <> 'Employee' OR EmployeeId IS NOT NULL)
);
CREATE UNIQUE INDEX IF NOT EXISTS ux_users_employee ON dbo.Users (EmployeeId) WHERE EmployeeId IS NOT NULL;
CREATE UNIQUE INDEX IF NOT EXISTS ux_users_email ON dbo.Users (Email) WHERE Email IS NOT NULL;

/* ---------- Application settings ---------- */
CREATE TABLE IF NOT EXISTS dbo.AppSettings (
    SettingKey    varchar(50)  PRIMARY KEY,
    SettingValue  varchar(500),
    UpdatedAt     timestamptz  NOT NULL DEFAULT now()
);

/* ---------- Product groups & products ---------- */
CREATE TABLE IF NOT EXISTS dbo.ProductGroups (
    ProductGroupId  integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    GroupCode       citext       NOT NULL UNIQUE,
    GroupName       varchar(100) NOT NULL,
    Description     varchar(500),
    IsActive        boolean      NOT NULL DEFAULT true,
    CreatedAt       timestamptz  NOT NULL DEFAULT now(),
    UpdatedAt       timestamptz  NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS dbo.Products (
    ProductId       integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ProductCode     citext       NOT NULL UNIQUE,
    ProductName     varchar(150) NOT NULL,
    ProductGroupId  integer      NOT NULL REFERENCES dbo.ProductGroups (ProductGroupId),
    Description     varchar(500),
    IsActive        boolean      NOT NULL DEFAULT true,
    CreatedAt       timestamptz  NOT NULL DEFAULT now(),
    UpdatedAt       timestamptz  NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ix_products_group ON dbo.Products (ProductGroupId);

/* ---------- Repeating work (templates) ---------- */
/* NextDueDate is the due date of the next item to create; the item is created LeadDays before it
   (its start date) by the background job. AnchorDay keeps "the 31st" from drifting after February. */
CREATE TABLE IF NOT EXISTS dbo.RecurringWork (
    RecurringId       integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Title             varchar(200) NOT NULL,
    Description       text,
    ProductGroupId    integer      REFERENCES dbo.ProductGroups (ProductGroupId),
    ProductId         integer      REFERENCES dbo.Products (ProductId),
    Priority          varchar(10)  NOT NULL DEFAULT 'Medium' CHECK (Priority IN ('Low', 'Medium', 'High', 'Urgent')),
    Frequency         varchar(10)  NOT NULL CHECK (Frequency IN ('Weekly', 'Monthly', 'Quarterly', 'Yearly')),
    AnchorDay         smallint     NOT NULL,
    NextDueDate       date         NOT NULL,
    LeadDays          smallint     NOT NULL DEFAULT 7 CHECK (LeadDays BETWEEN 0 AND 90),
    EndDate           date,
    IsActive          boolean      NOT NULL DEFAULT true,
    CreatedByUserId   integer      NOT NULL REFERENCES dbo.Users (UserId),
    CreatedAt         timestamptz  NOT NULL DEFAULT now(),
    UpdatedAt         timestamptz  NOT NULL DEFAULT now(),
    LastCreatedAt     timestamptz
);
CREATE INDEX IF NOT EXISTS ix_recurringwork_next ON dbo.RecurringWork (IsActive, NextDueDate);

CREATE TABLE IF NOT EXISTS dbo.RecurringWorkAssignees (
    RecurringId  integer NOT NULL REFERENCES dbo.RecurringWork (RecurringId),
    EmployeeId   integer NOT NULL REFERENCES dbo.Employees (EmployeeId),
    PRIMARY KEY (RecurringId, EmployeeId)
);

/* ---------- Work items ---------- */
/* RowVer is the optimistic-concurrency token: every update gets a new value (trigger below), so a
   second save based on stale data is rejected with "changed by someone else". */
CREATE SEQUENCE IF NOT EXISTS dbo.rowver_seq;

CREATE TABLE IF NOT EXISTS dbo.WorkItems (
    WorkId           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- Human-readable number derived from the id, e.g. WD-000042
    WorkNo           varchar(20) GENERATED ALWAYS AS ('WD-' || lpad(WorkId::text, 6, '0')) STORED,
    Title            varchar(200) NOT NULL,
    Description      text,
    ProductGroupId   integer      REFERENCES dbo.ProductGroups (ProductGroupId),
    ProductId        integer      REFERENCES dbo.Products (ProductId),
    Priority         varchar(10)  NOT NULL DEFAULT 'Medium' CHECK (Priority IN ('Low', 'Medium', 'High', 'Urgent')),
    Status           varchar(20)  NOT NULL DEFAULT 'Pending'
                                  CHECK (Status IN ('Pending', 'In Progress', 'On Hold', 'Completed', 'Closed', 'Reopened')),
    StartDate        date,
    DueDate          date,
    CreatedByUserId  integer      NOT NULL REFERENCES dbo.Users (UserId),
    CreatedAt        timestamptz  NOT NULL DEFAULT now(),
    UpdatedAt        timestamptz  NOT NULL DEFAULT now(),
    ClosedAt         timestamptz,
    RecurringId      integer      REFERENCES dbo.RecurringWork (RecurringId),
    RowVer           bigint       NOT NULL DEFAULT nextval('dbo.rowver_seq'),
    CONSTRAINT ck_workitems_dates CHECK (StartDate IS NULL OR DueDate IS NULL OR DueDate >= StartDate)
);
CREATE UNIQUE INDEX IF NOT EXISTS ux_workitems_workno ON dbo.WorkItems (WorkNo);
CREATE INDEX IF NOT EXISTS ix_workitems_status_due ON dbo.WorkItems (Status, DueDate);
CREATE INDEX IF NOT EXISTS ix_workitems_due ON dbo.WorkItems (DueDate);
CREATE INDEX IF NOT EXISTS ix_workitems_created ON dbo.WorkItems (CreatedAt);
CREATE INDEX IF NOT EXISTS ix_workitems_updated ON dbo.WorkItems (UpdatedAt);
CREATE INDEX IF NOT EXISTS ix_workitems_product ON dbo.WorkItems (ProductId);
CREATE INDEX IF NOT EXISTS ix_workitems_group ON dbo.WorkItems (ProductGroupId);
CREATE INDEX IF NOT EXISTS ix_workitems_recurring ON dbo.WorkItems (RecurringId) WHERE RecurringId IS NOT NULL;

CREATE OR REPLACE FUNCTION dbo.bump_rowver() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    NEW.RowVer := nextval('dbo.rowver_seq');
    RETURN NEW;
END $$;
CREATE OR REPLACE TRIGGER trg_workitems_rowver BEFORE UPDATE ON dbo.WorkItems
    FOR EACH ROW EXECUTE FUNCTION dbo.bump_rowver();

/* ---------- Work assignments (one work item -> many employees) ---------- */
CREATE TABLE IF NOT EXISTS dbo.WorkAssignments (
    AssignmentId        integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    WorkId              integer     NOT NULL REFERENCES dbo.WorkItems (WorkId),
    EmployeeId          integer     NOT NULL REFERENCES dbo.Employees (EmployeeId),
    AssignedByUserId    integer     NOT NULL REFERENCES dbo.Users (UserId),
    AssignedAt          timestamptz NOT NULL DEFAULT now(),
    IsActive            boolean     NOT NULL DEFAULT true,
    UnassignedAt        timestamptz,
    UnassignedByUserId  integer     REFERENCES dbo.Users (UserId)
);
-- The same employee can be actively assigned to a work item only once
CREATE UNIQUE INDEX IF NOT EXISTS ux_workassignments_active ON dbo.WorkAssignments (WorkId, EmployeeId) WHERE IsActive;
CREATE INDEX IF NOT EXISTS ix_workassignments_employee ON dbo.WorkAssignments (EmployeeId, IsActive) INCLUDE (WorkId);

/* ---------- Work status history / activity log ---------- */
CREATE TABLE IF NOT EXISTS dbo.WorkStatusHistory (
    HistoryId        bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    WorkId           integer      NOT NULL REFERENCES dbo.WorkItems (WorkId),
    EntryType        varchar(20)  NOT NULL DEFAULT 'StatusChange'
                                  CHECK (EntryType IN ('Created', 'StatusChange', 'Note', 'Assignment', 'Edit', 'Attachment')),
    OldStatus        varchar(20),
    NewStatus        varchar(20)  NOT NULL,
    ChangedByUserId  integer      NOT NULL REFERENCES dbo.Users (UserId),
    Notes            varchar(2000),
    ChangedAt        timestamptz  NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ix_workstatushistory_work ON dbo.WorkStatusHistory (WorkId, ChangedAt);
CREATE INDEX IF NOT EXISTS ix_workstatushistory_changed ON dbo.WorkStatusHistory (ChangedAt) INCLUDE (WorkId, EntryType, NewStatus);

/* ---------- Files attached to work items ---------- */
/* Kept in the company's own schema. Deleting a file erases its content but keeps the row and a
   history entry, so the activity log stays complete. */
CREATE TABLE IF NOT EXISTS dbo.WorkAttachments (
    AttachmentId      integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    WorkId            integer      NOT NULL REFERENCES dbo.WorkItems (WorkId),
    FileName          varchar(255) NOT NULL,
    ContentType       varchar(100) NOT NULL,
    SizeBytes         integer      NOT NULL,
    Content           bytea,
    UploadedByUserId  integer      NOT NULL REFERENCES dbo.Users (UserId),
    CreatedAt         timestamptz  NOT NULL DEFAULT now(),
    DeletedAt         timestamptz,
    DeletedByUserId   integer      REFERENCES dbo.Users (UserId)
);
CREATE INDEX IF NOT EXISTS ix_workattachments_work ON dbo.WorkAttachments (WorkId) INCLUDE (FileName, SizeBytes, DeletedAt);

/* ---------- Sessions & security log ---------- */
CREATE TABLE IF NOT EXISTS dbo.Sessions (
    SessionId   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    TokenHash   char(64)     NOT NULL UNIQUE,  -- SHA-256 of the cookie token; the raw token is never stored
    UserId      integer      NOT NULL REFERENCES dbo.Users (UserId),
    CreatedAt   timestamptz  NOT NULL DEFAULT now(),
    LastSeenAt  timestamptz  NOT NULL DEFAULT now(),
    ExpiresAt   timestamptz  NOT NULL,
    RevokedAt   timestamptz,
    IpAddress   varchar(64),
    UserAgent   varchar(300)
);
CREATE INDEX IF NOT EXISTS ix_sessions_user ON dbo.Sessions (UserId) INCLUDE (RevokedAt, ExpiresAt);

CREATE TABLE IF NOT EXISTS dbo.SecurityEvents (
    EventId    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    EventType  varchar(50)  NOT NULL,
    UserId     integer,
    Username   varchar(50),
    IpAddress  varchar(64),
    Details    varchar(500),
    CreatedAt  timestamptz  NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ix_securityevents_created ON dbo.SecurityEvents (CreatedAt);

/* ---------- Chat ---------- */
/* One "Company" conversation (everyone in this client), one "Direct" conversation per pair of users,
   and any number of named "Group" conversations. */
CREATE TABLE IF NOT EXISTS dbo.ChatConversations (
    ConversationId   integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Kind             varchar(10)  NOT NULL CHECK (Kind IN ('Company', 'Direct', 'Group')),
    Title            varchar(100),          -- group name
    -- Direct chats: "<lower UserId>:<higher UserId>"; the company chat: "*"
    DirectKey        varchar(30),
    CreatedByUserId  integer      REFERENCES dbo.Users (UserId),
    CreatedAt        timestamptz  NOT NULL DEFAULT now(),
    LastMessageAt    timestamptz
);
CREATE UNIQUE INDEX IF NOT EXISTS ux_chatconversations_directkey ON dbo.ChatConversations (DirectKey) WHERE DirectKey IS NOT NULL;

CREATE TABLE IF NOT EXISTS dbo.ChatMembers (
    ConversationId     integer     NOT NULL REFERENCES dbo.ChatConversations (ConversationId),
    UserId             integer     NOT NULL REFERENCES dbo.Users (UserId),
    -- Messages up to this id have been read by the user (drives unread counts)
    LastReadMessageId  bigint      NOT NULL DEFAULT 0,
    JoinedAt           timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (ConversationId, UserId)
);
CREATE INDEX IF NOT EXISTS ix_chatmembers_user ON dbo.ChatMembers (UserId);

CREATE TABLE IF NOT EXISTS dbo.ChatMessages (
    MessageId       bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ConversationId  integer       NOT NULL REFERENCES dbo.ChatConversations (ConversationId),
    SenderUserId    integer       NOT NULL REFERENCES dbo.Users (UserId),
    Body            varchar(2000) NOT NULL,
    CreatedAt       timestamptz   NOT NULL DEFAULT now(),
    EditedAt        timestamptz,
    DeletedAt       timestamptz
);
CREATE INDEX IF NOT EXISTS ix_chatmessages_conversation ON dbo.ChatMessages (ConversationId, MessageId) INCLUDE (SenderUserId, CreatedAt);

/* Files sent in chat (one per message). Content is erased when the message is deleted. */
CREATE TABLE IF NOT EXISTS dbo.ChatAttachments (
    AttachmentId  integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    MessageId     bigint        NOT NULL UNIQUE REFERENCES dbo.ChatMessages (MessageId),
    FileName      varchar(255)  NOT NULL,
    ContentType   varchar(100)  NOT NULL,
    SizeBytes     integer       NOT NULL,
    Content       bytea,
    CreatedAt     timestamptz   NOT NULL DEFAULT now()
);

/* ---------- In-app notifications ---------- */
CREATE TABLE IF NOT EXISTS dbo.Notifications (
    NotificationId  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    UserId          integer      NOT NULL REFERENCES dbo.Users (UserId),
    Kind            varchar(20)  NOT NULL
                                 CHECK (Kind IN ('Assigned', 'Status', 'Note', 'Mention', 'Attachment', 'DueToday', 'Overdue', 'Created')),
    WorkId          integer      REFERENCES dbo.WorkItems (WorkId),
    ActorUserId     integer      REFERENCES dbo.Users (UserId),
    Message         varchar(400) NOT NULL,
    CreatedAt       timestamptz  NOT NULL DEFAULT now(),
    ReadAt          timestamptz
);
CREATE INDEX IF NOT EXISTS ix_notifications_user ON dbo.Notifications (UserId, NotificationId DESC) INCLUDE (ReadAt);
CREATE INDEX IF NOT EXISTS ix_notifications_work ON dbo.Notifications (WorkId, Kind, UserId) INCLUDE (CreatedAt);
