/*
  Q-WorkDone - shared tables (PostgreSQL 14+), in the "public" schema.

  The Client ID entered at sign-in is looked up in Clients to find that company's schema.
  SchemaVersions records which version of client.sql each schema has, so the app upgrades
  schemas only when it is newer. Idempotent; the app runs it at start-up.
*/

-- Case-insensitive text for usernames, e-mails and codes (a trusted extension: no superuser needed)
CREATE EXTENSION IF NOT EXISTS citext;

CREATE TABLE IF NOT EXISTS public.Clients (
    ClientId     varchar(30)  PRIMARY KEY,           -- stored upper-case
    CompanyName  varchar(150) NOT NULL,
    SchemaName   varchar(63)  NOT NULL UNIQUE,       -- schema holding the company's tables, e.g. wd_acme
    IsActive     boolean      NOT NULL DEFAULT true,
    CreatedAt    timestamptz  NOT NULL DEFAULT now(),
    UpdatedAt    timestamptz  NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.SchemaVersions (
    SchemaName  varchar(63) PRIMARY KEY,
    Version     integer     NOT NULL,
    UpdatedAt   timestamptz NOT NULL DEFAULT now()
);

-- Sign-in attempts with an unknown Client ID are recorded here (they belong to no company)
CREATE TABLE IF NOT EXISTS public.SecurityEvents (
    EventId    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    EventType  varchar(50)  NOT NULL,
    UserId     integer,
    Username   varchar(50),
    IpAddress  varchar(64),
    Details    varchar(500),
    CreatedAt  timestamptz  NOT NULL DEFAULT now()
);
